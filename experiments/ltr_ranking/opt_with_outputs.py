"""Published LTR predictor on the 113 smoke-trace requests, with the model's own earlier outputs in the prompt.

Same predictor and usage as opt_zero_shot.py. Difference: the prompt for step k is now the full history a scheduler
sees at serving time, built from replay_outputs.py: system prompt + task + for every earlier step (model output
generated by our llama.cpp server, i.e. its reasoning and tool call) + (tool result). Step 0 is unchanged.

Inputs scored (OPT max 2,048 tokens):
  full_head  full served history text, first 2,048 OPT tokens (paper's truncation)
  full_tail  full served history text, last 2,048 OPT tokens (latest tool result and the end of the last output)
  user_head  same history without the system prompt / chat template, first 2,048
  user_tail  same history without the system prompt / chat template, last 2,048
Score -> tokens mappings, all evaluated on the 113 test requests:
  LOTO        fitted by leave-one-task-out cross-validation on the 113 (each task's requests predicted by a mapping
              fitted on the other 49 tasks' requests): constant median, one factor, linear, log-linear, isotonic
  calibration the mappings fitted in opt_zero_shot.py on 2,283 calibration requests (prompts without earlier
              outputs, so a mismatch for later steps; reported for reference)
The true output length is only the target, and the training data of the LOTO fits never include the predicted task.
"""

import json
from pathlib import Path

import numpy as np
import pandas as pd
import torch
from tokenizers import Tokenizer
from transformers import OPTForSequenceClassification

from experiments.ltr_ranking.opt_zero_shot import (CKPT, MAXLEN, QWEN_TOK, READABLE, TEST, errors, mappings,
                                                   opt_tokenizer, rank_metrics)

ROOT = Path(__file__).resolve().parents[2]
REPLAY = ROOT / "results/ltr_ranking/replay_outputs/outputs.jsonl"
ZERO = ROOT / "results/ltr_ranking/opt_zero_shot"
OUT = ROOT / "results/ltr_ranking/opt_with_outputs"
VARIANTS = (("full_head", "full_text", "right"), ("full_tail", "full_text", "left"),
            ("user_head", "user_text", "right"), ("user_tail", "user_text", "left"))


def build() -> pd.DataFrame:
    qwen = Tokenizer.from_file(str(QWEN_TOK))
    tasks = [json.loads(l) for l in TEST.open()]
    readable = {r["task_id"]: r for r in map(json.loads, READABLE.open())}
    outs = {(r["task_id"], r["step"]): r for r in map(json.loads, REPLAY.open())}
    rows = []
    for t in tasks:
        r = readable[t["task_id"]]
        ids, user = [], r["initial_prompt"]
        for k, s in enumerate(t["steps"]):
            if k > 0:
                prev = outs[(t["task_id"], k - 1)]["tokens"]
                ids = ids + prev
                user = user + "\n\n" + qwen.decode(prev) + "\n\n" + (r["steps"][k - 1]["tool"] or {}).get("result_text", "")
            ids = ids + s["input"]
            o = outs[(t["task_id"], k)]
            assert o["n_prompt"] == len(ids) and o["n_gen"] == s["n_gen"], (t["task_id"], k)
            rows.append({"task_id": t["task_id"], "cls": t["cls"], "step": k, "n_steps": len(t["steps"]),
                         "prompt_tokens_qwen": len(ids), "n_gen": s["n_gen"],
                         "full_text": qwen.decode(ids, skip_special_tokens=False), "user_text": user})
    return pd.DataFrame(rows)


@torch.no_grad()
def score(df):
    tok = opt_tokenizer()
    model = OPTForSequenceClassification.from_pretrained(CKPT).cuda().eval()
    enc = {c: [tok.encode(t).ids for t in df[c]] for c in ("full_text", "user_text")}
    out = {}
    for name, col, side in VARIANTS:
        s = []
        for ids in enc[col]:
            ids = ids[:MAXLEN - 1] if side == "right" else ids[-(MAXLEN - 1):]
            x = torch.tensor([[2] + ids], device="cuda")
            s.append(float(model(input_ids=x, attention_mask=torch.ones_like(x)).logits[0, 0]))
        out[f"score_{name}"] = s
    out["opt_tokens_full"] = [len(x) + 1 for x in enc["full_text"]]
    out["opt_tokens_user"] = [len(x) + 1 for x in enc["user_text"]]
    return df.assign(**out)


def loto(df, sc):
    preds = {m: np.zeros(len(df)) for m in ("const_median", "factor", "linear", "loglinear", "isotonic")}
    for tid in df.task_id.unique():
        tr, te = df.task_id != tid, (df.task_id == tid).values
        maps, _ = mappings(df.loc[tr, sc].values, df.loc[tr, "n_gen"].values.astype(float))
        for m in preds:
            preds[m][te] = maps[m](df.loc[te, sc].values)
    return preds


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    df = score(build())
    assert len(df) == 113
    calib = json.loads((ZERO / "meta.json").read_text())["mapping_params"]
    rows, by_step = [], []
    for name, _, _ in VARIANTS:
        sc = f"score_{name}"
        preds = loto(df, sc)
        for m, p in preds.items():
            rows.append({"input": name, "mapping": m, "fit": "leave-one-task-out (113)", **errors(df.n_gen, p),
                         **rank_metrics(df.n_gen, df[sc])})
            df[f"pred_{m}_{name}"] = p
        if name in calib:
            c = calib[name]
            for m, p in (("loglinear", np.exp(c["loglinear_a"] + c["loglinear_b"] * df[sc])),
                         ("linear", np.clip(c["linear_a"] + c["linear_b"] * df[sc], 1, None))):
                rows.append({"input": name, "mapping": m, "fit": "calibration (2,283, no earlier outputs)",
                             **errors(df.n_gen, p), **rank_metrics(df.n_gen, df[sc])})
        for sub, g in (("step 0", df[df.step == 0]), ("steps 1+", df[df.step > 0])):
            by_step.append({"input": name, "subset": sub, "n": len(g), **rank_metrics(g.n_gen, g[sc]),
                            **{f"MAE_{m}": errors(g.n_gen, g[f"pred_{m}_{name}"])["MAE"]
                               for m in ("const_median", "loglinear", "isotonic")}})
    # same requests without earlier outputs (opt_zero_shot), for a direct comparison of ranking quality
    z = pd.read_csv(ZERO / "predictions.csv")
    z = z[z.split == "test"].set_index(["task_id", "step"]).loc[list(zip(df.task_id, df.step))]
    cmp = []
    for v in ("full_head", "full_tail", "user_head"):
        for sub, m in (("all", np.ones(len(df), bool)), ("step 0", (df.step == 0).values), ("steps 1+", (df.step > 0).values)):
            cmp.append({"input": v, "subset": sub, "tau_without_outputs": rank_metrics(df.n_gen[m], z[f"score_{v}"].values[m])["kendall_tau"],
                        "tau_with_outputs": rank_metrics(df.n_gen[m], df[f"score_{v}"].values[m])["kendall_tau"]})
    res, by_step, cmp = pd.DataFrame(rows), pd.DataFrame(by_step), pd.DataFrame(cmp)
    df.drop(columns=["full_text", "user_text"]).to_csv(OUT / "predictions.csv", index=False)
    res.to_csv(OUT / "errors.csv", index=False)
    by_step.to_csv(OUT / "by_step.csv", index=False)
    cmp.to_csv(OUT / "tau_with_vs_without_outputs.csv", index=False)
    q = df[["n_gen"] + [f"pred_isotonic_{v}" for v, _, _ in VARIANTS]].quantile([.1, .25, .5, .75, .9])
    meta = {"n": len(df), "pct_truncated_full": float((df.opt_tokens_full > MAXLEN).mean() * 100),
            "pct_truncated_user": float((df.opt_tokens_user > MAXLEN).mean() * 100),
            "opt_tokens_full_steps1_median": float(df[df.step > 0].opt_tokens_full.median()),
            "quantiles_true_vs_isotonic": q.to_dict(), "doc": __doc__}
    (OUT / "meta.json").write_text(json.dumps(meta, indent=2, default=float))
    with pd.option_context("display.width", 250, "display.max_columns", 20, "display.float_format", "{:.2f}".format):
        print(res.to_string(index=False)); print(); print(by_step.to_string(index=False)); print()
        print(cmp.to_string(index=False)); print(); print(q.round(0)); print(json.dumps({k: v for k, v in meta.items()
                                                                                        if k.startswith(("pct", "opt"))}))


if __name__ == "__main__":
    main()
